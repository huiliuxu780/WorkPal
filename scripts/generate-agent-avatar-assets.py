"""Compile checked-in frozen SVGs into safe React-renderable node data.

Run after replacing a reviewed asset. The original SVG files remain byte-identical
to the design source; this generated module never accepts runtime/user markup.
"""

from __future__ import annotations

import json
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "packages/ui-web/src/agent-avatar/assets"
OUTPUT = ROOT / "packages/ui-web/src/agent-avatar/assets.generated.ts"
TAGS = {"svg", "g", "path", "rect"}


def node(element: ElementTree.Element) -> dict[str, object]:
    tag = element.tag.rsplit("}", 1)[-1]
    if tag not in TAGS:
        raise ValueError(f"Unexpected SVG element: {tag}")
    if element.text and element.text.strip():
        raise ValueError(f"Unexpected SVG text in {tag}")
    attrs = {}
    for raw_key, value in element.attrib.items():
        key = raw_key.rsplit("}", 1)[-1]
        if key == "style" or key.lower().startswith("on") or key in {"href", "xlink:href"}:
            raise ValueError(f"Unsafe SVG attribute: {key}")
        words = key.split("-") if not key.startswith("data-") else [key]
        key = words[0] + "".join(word.title() for word in words[1:])
        attrs[key] = value
    children = [node(child) for child in element]
    return {"tag": tag, "attrs": attrs, "children": children}


def load(filename: str) -> dict[str, object]:
    root = node(ElementTree.parse(ASSETS / filename).getroot())
    root["attrs"]["xmlns"] = "http://www.w3.org/2000/svg"
    return root


def main() -> None:
    characters = ("dot", "treble", "wave", "bounce")
    colors = ("orange", "blue", "purple", "brown", "pink", "ink")
    tiers = {"L": "", "S": "-s", "XS": "-xs", "compact": "-16"}
    roles = {name: f"{index}-{name}" for index, name in enumerate(characters, 1)}
    variants = {
        "characters": {name: {color: {tier: load(f"{roles[name]}-{color}{suffix}.svg") for tier, suffix in tiers.items()} for color in colors} for name in characters},
        "laptops": {color: {tier: load(f"props/laptop-{color}{suffix}.svg") for tier, suffix in (("L", ""), ("S", "-s"))} for color in colors},
        "props": {name: load(f"props/{name}.svg") for name in ("card", "question", "question-dark")},
        "xeyes": {name: {color: {tier: load(f"props/xeyes-{roles[name]}-{color}{suffix}.svg") for tier, suffix in (("L", ""), ("S", "-s"))} for color in colors} for name in characters},
        "static": {p.stem: load(str(p.relative_to(ASSETS))) for p in sorted((ASSETS / "static").glob("*.svg"))},
    }
    # XS has no supplied failure overlay. Reuse frozen X paths, with XS fit/color.
    anchors = json.loads((ASSETS / "anchors.json").read_text())["anchors"]
    palette = json.loads((ASSETS / "palette.json").read_text())
    for name in characters:
        fit = anchors[roles[name]]["XS"]["fit"]
        for color in colors:
            overlay = load(f"props/xeyes-{roles[name]}-{color}-s.svg")
            def adapt(current):
                attrs = current["attrs"]
                if attrs.get("id") == "fit":
                    attrs["transform"] = f'translate(50 50) scale({fit["s"]}) translate({-fit["cx"]} {-fit["cy"]})'
                if attrs.get("stroke") == palette["dark"]["S"][color]:
                    attrs["stroke"] = palette["dark"]["XS"][color]
                for child in current["children"]:
                    adapt(child)
            adapt(overlay)
            variants["xeyes"][name][color]["XS"] = overlay
    output = (
        "// Generated by scripts/generate-agent-avatar-assets.py. Do not edit.\n"
        "export type SvgNode = { tag: string; attrs: Record<string, string>; children: SvgNode[] };\n"
        "type Character = \"dot\" | \"treble\" | \"wave\" | \"bounce\";\n"
        "type Color = \"orange\" | \"blue\" | \"purple\" | \"brown\" | \"pink\" | \"ink\";\n"
        "export type AvatarTier = \"L\" | \"S\" | \"XS\" | \"compact\";\n"
        "export const avatarAssets: { characters: Record<Character, Record<Color, Record<AvatarTier, SvgNode>>>; laptops: Record<Color, Record<\"L\" | \"S\", SvgNode>>; props: Record<\"card\" | \"question\" | \"question-dark\", SvgNode>; xeyes: Record<Character, Record<Color, Record<\"L\" | \"S\" | \"XS\", SvgNode>>>; static: Record<string, SvgNode> } = "
        + json.dumps(variants, ensure_ascii=False, separators=(",", ":")) + ";\n"
        + "export const avatarAnchors = " + (ASSETS / "anchors.json").read_text() + " as const;\n"
        + "export const avatarPalette = " + (ASSETS / "palette.json").read_text() + " as const;\n"
    )
    OUTPUT.write_text(output)


if __name__ == "__main__":
    main()
