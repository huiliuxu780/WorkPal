import { type ChildProcess, spawn } from "node:child_process";
import { createServer, request as httpRequest, type Server } from "node:http";
import { mkdtemp, rm } from "node:fs/promises";
import type { AddressInfo } from "node:net";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import type { AgentRunRequest, AgentRuntimeEvent } from "@rakazo/adapter-kit";
import {
  buildRunOrchestration,
  orchestrationExecution,
  resolveTurnPolicy,
  turnPolicyFromRun,
} from "@rakazo/core";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { AgentScopeAgentRuntime } from "./agentscope-runtime.js";

// TurnPolicy v2 cross-language acceptance: the policy is generated by the real
// TypeScript builders (resolveTurnPolicy / buildRunOrchestration /
// turnPolicyFromRun), travels over the real HTTP wire through a test-side
// recorder proxy, and is enforced by the real Java AgentScope runtime. No
// production debug endpoint is added; the recorder is test infrastructure.
const serviceDir = fileURLToPath(new URL("../../../services/agent-runtime/", import.meta.url));
const runtimeJar = join(serviceDir, "target/agent-runtime-0.1.0.jar");

type WireRunRequest = Record<string, any>;
type RecordedRun = { original: WireRunRequest; sent: WireRunRequest };

describe("TurnPolicy v2 TypeScript to Java acceptance", () => {
  let child: ChildProcess;
  let stateDir: string;
  let runtime: AgentScopeAgentRuntime;
  let modelUrl: string;
  let modelServer: Server;
  let proxy: Server;
  let proxyUrl: string;
  const modelRequests: Array<{
    model: string;
    messages: Array<{ role: string; content: unknown }>;
    tools?: Array<{ function: { name: string } }>;
  }> = [];
  const runRequests: RecordedRun[] = [];
  let wireTransform: ((body: WireRunRequest) => WireRunRequest) | null = null;
  const subagentToolCalls: string[] = [];

  const sse = (
    res: { writeHead: Function; write: Function; end: Function },
    model: string,
    delta: Record<string, unknown>,
    finish: "stop" | "tool_calls",
  ) => {
    res.writeHead(200, { "content-type": "text/event-stream" });
    for (const [part, finishReason] of [
      [delta, null],
      [{}, finish],
    ] as Array<[Record<string, unknown>, string | null]>) {
      res.write(
        `data: ${JSON.stringify({
          id: "turnpolicy-fixture",
          object: "chat.completion.chunk",
          model,
          choices: [{ index: 0, delta: part, finish_reason: finishReason }],
        })}\n\n`,
      );
    }
    res.end("data: [DONE]\n\n");
  };

  const toolCall = (id: string, name: string, args: Record<string, unknown>) => ({
    tool_calls: [
      { index: 0, id, type: "function", function: { name, arguments: JSON.stringify(args) } },
    ],
  });

  const userText = (input: { messages: Array<{ role: string; content: unknown }> }) =>
    input.messages
      .filter((message) => message.role === "user")
      .map((message) => JSON.stringify(message.content))
      .join("\n");
  /** The newest user turn; restored sessions replay earlier turns verbatim. */
  const lastUserText = (input: { messages: Array<{ role: string; content: unknown }> }) => {
    for (let index = input.messages.length - 1; index >= 0; index--) {
      const message = input.messages[index]!;
      if (message.role === "user") return JSON.stringify(message.content);
    }
    return "";
  };
  const transcript = (input: { messages: unknown }) => JSON.stringify(input.messages);

  beforeAll(async () => {
    stateDir = await mkdtemp(join(tmpdir(), "workpal-turnpolicy-v2-"));
    modelServer = createServer((req, res) => {
      let body = "";
      req.on("data", (chunk) => {
        body += chunk;
      });
      req.on("end", () => {
        const input = JSON.parse(body);
        modelRequests.push(input);
        const respond = (delta: Record<string, unknown>, finish: "stop" | "tool_calls") =>
          sse(res, input.model, delta, finish);
        const all = transcript(input);
        // The refused background spawn surfaces Java's hard-count message; the
        // parent then finishes directly without any helper having run.
        if (all.includes("Delegation budget exceeded")) {
          respond({ content: "SPAWN_BUDGET_BOUND" }, "stop");
          return;
        }
        if (userText(input).includes("DEPTH_ZERO_FIXTURE")) {
          const toolTurns = input.messages.filter(
            (message: { role: string }) => message.role === "tool",
          ).length;
          if (toolTurns === 0) {
            respond(
              toolCall("depth-spawn-a", "agent_spawn", {
                agent_id: "helper",
                task: "DEPTH_ZERO_TASK",
              }),
              "tool_calls",
            );
            return;
          }
          if (toolTurns === 1) {
            respond(
              toolCall("depth-spawn-b", "agent_spawn", {
                agent_id: "helper",
                task: "DEPTH_ZERO_TASK",
                timeout_seconds: 0,
              }),
              "tool_calls",
            );
            return;
          }
          respond({ content: "DEPTH_ZERO_BOUND" }, "stop");
          return;
        }
        if (userText(input).includes("SPAWN_BUDGET_FIXTURE")) {
          // AG-02: native delegation is suspended, so agent_spawn is never offered. The model
          // still attempts it once (a direct call bypassing visibility); the runtime refuses it
          // (unregistered tool), which surfaces as a tool turn, and the parent then finishes
          // without any helper having run. The budget/depth enforcement this scenario used to
          // exercise end-to-end is covered in-JVM by InterruptibleTaskRepositoryTest.
          const toolTurns = input.messages.filter(
            (message: { role: string }) => message.role === "tool",
          ).length;
          if (toolTurns === 0) {
            respond(
              toolCall("spawn-a", "agent_spawn", {
                agent_id: "helper",
                task: "SPAWN_BG_MARKER",
                timeout_seconds: 0,
              }),
              "tool_calls",
            );
            return;
          }
          respond({ content: "SPAWN_SUSPENDED_NO_HELPER" }, "stop");
          return;
        }
        if (lastUserText(input).includes("RESUME_FIXTURE_B")) {
          respond({ content: "RESUME_B_OK" }, "stop");
          return;
        }
        if (lastUserText(input).includes("RESUME_FIXTURE_A")) {
          respond({ content: "RESUME_A_OK" }, "stop");
          return;
        }
        if (userText(input).includes("CORRUPT_SNAPSHOT_FIXTURE")) {
          respond({ content: "CORRUPT_SNAPSHOT_NO_PLANNING" }, "stop");
          return;
        }
        respond({ content: "UNEXPECTED_FIXTURE_TURN" }, "stop");
      });
    });
    await new Promise<void>((resolve) => modelServer.listen(0, "127.0.0.1", resolve));
    modelUrl = `http://127.0.0.1:${(modelServer.address() as AddressInfo).port}/v1`;

    // Boot the real Java runtime on a free loopback port.
    const probe = createServer();
    await new Promise<void>((resolve) => probe.listen(0, "127.0.0.1", resolve));
    const javaPort = (probe.address() as AddressInfo).port;
    await new Promise<void>((resolve) => probe.close(() => resolve()));
    const javaUrl = `http://127.0.0.1:${javaPort}`;
    child = spawn("java", ["-jar", runtimeJar], {
      cwd: serviceDir,
      env: {
        ...process.env,
        AGENT_RUNTIME_HOST: "127.0.0.1",
        AGENT_RUNTIME_PORT: String(javaPort),
        AGENT_RUNTIME_DATA_DIR: stateDir,
      },
      stdio: ["ignore", "ignore", "pipe"],
    });
    let logs = "";
    child.stderr?.on("data", (chunk) => {
      logs += chunk.toString();
    });
    let ready = false;
    for (let attempt = 0; attempt < 100; attempt++) {
      if (child.exitCode !== null) throw new Error(`Java runtime exited ${child.exitCode}: ${logs}`);
      try {
        ready = (await fetch(`${javaUrl}/health`)).ok;
      } catch {
        /* starting */
      }
      if (ready) break;
      await new Promise((resolve) => setTimeout(resolve, 100));
    }
    if (!ready) throw new Error(`Java runtime startup timed out: ${logs}`);

    // Test-side recorder proxy in front of Java: records (and for the negative
    // case corrupts) the POST /v1/runs wire payload, streams everything else.
    proxy = createServer((req, res) => {
      const chunks: Buffer[] = [];
      req.on("data", (chunk) => chunks.push(chunk as Buffer));
      req.on("end", () => {
        let payload = Buffer.concat(chunks);
        if (req.method === "POST" && req.url === "/v1/runs" && payload.length > 0) {
          const original = JSON.parse(payload.toString("utf8")) as WireRunRequest;
          const sent = wireTransform ? wireTransform(structuredClone(original)) : original;
          runRequests.push({ original, sent });
          payload = Buffer.from(JSON.stringify(sent), "utf8");
        }
        const headers: Record<string, string | number> = {
          "content-type": req.headers["content-type"] ?? "application/json",
          "content-length": payload.length,
        };
        if (req.headers.accept) headers.accept = String(req.headers.accept);
        if (req.headers.authorization) headers.authorization = String(req.headers.authorization);
        const proxyRequest = httpRequest(`${javaUrl}${req.url}`, { method: req.method, headers }, (upstream) => {
          res.writeHead(upstream.statusCode ?? 502, upstream.headers);
          upstream.pipe(res);
        });
        proxyRequest.on("error", (error) => {
          res.writeHead(502, { "content-type": "text/plain" });
          res.end(String(error));
        });
        proxyRequest.end(payload);
      });
    });
    await new Promise<void>((resolve) => proxy.listen(0, "127.0.0.1", resolve));
    proxyUrl = `http://127.0.0.1:${(proxy.address() as AddressInfo).port}`;
    runtime = new AgentScopeAgentRuntime({ baseUrl: proxyUrl });
  }, 120_000);

  afterAll(async () => {
    if (child && child.exitCode === null) {
      await new Promise<void>((resolve) => {
        child.once("exit", () => resolve());
        child.kill("SIGTERM");
      });
    }
    // Only wait on resources that were actually created: a beforeAll that died
    // part-way (for example no Java on PATH) must not add a hook timeout to the
    // startup error it already reported.
    if (proxy) await new Promise<void>((resolve) => proxy.close(() => resolve()));
    if (modelServer) await new Promise<void>((resolve) => modelServer.close(() => resolve()));
    if (stateDir) await rm(stateDir, { recursive: true, force: true });
  });

  const context = () => ({
    operationId: "turnpolicy-v2",
    traceId: "turnpolicy-v2",
    userId: "user-tp",
    spaceId: "space-tp",
  });

  /** The immutable creation-time snapshot a chat Run persists, with a tightened helper budget. */
  const storedOrchestration = () => {
    const base = resolveTurnPolicy({ source: "chat", ownerBotId: "bot-tp" });
    return buildRunOrchestration({
      kind: "direct",
      ownerBotId: "bot-tp",
      responseMode: "single",
      execution: {
        ...orchestrationExecution(base),
        // A persisted budget that disagrees with the legacy delegation block:
        // the effective values must be the tightened minimums on both sides
        // (maxChildAgents 3→0, maxDepth 5→1 against delegation.maxDepth 1).
        budget: { ...base.budget, maxChildAgents: 0, maxDepth: 5 },
      },
    });
  };

  const request = (input: {
    runId: string;
    threadId: string;
    prompt: string;
    turnPolicy: AgentRunRequest["turnPolicy"];
    tools?: AgentRunRequest["tools"];
  }): AgentRunRequest => ({
    botId: "bot-tp",
    threadId: input.threadId,
    runId: input.runId,
    sourceMessageId: input.runId,
    prompt: input.prompt,
    instructions: "Fixture instructions.",
    history: [],
    tools: input.tools ?? [],
    turnPolicy: input.turnPolicy,
    model: {
      provider: "openai-compatible",
      id: "turnpolicy-fixture",
      apiKey: "fixture",
      baseUrl: modelUrl,
    },
    executeTool: async (name) => {
      subagentToolCalls.push(name);
      return { ok: true, result: "backend fallback" };
    },
  });

  const consume = async (input: AgentRunRequest) => {
    const events: AgentRuntimeEvent[] = [];
    for await (const event of runtime.run(input, context())) events.push(event);
    return events;
  };

  const subagentTool = {
    name: "run_subagent",
    description: "Run an isolated helper subagent.",
    inputSchema: {
      type: "object" as const,
      properties: { task: { type: "string" } },
    },
    readOnly: false,
  };

  it("suspends native delegation while still serializing the tightened v2 budget to Java", async () => {
    const policy = turnPolicyFromRun({
      trigger: "user",
      ownerBotId: "bot-tp",
      orchestration: storedOrchestration(),
    });
    expect(policy.version).toBe("v2");
    const events = await consume(
      request({
        runId: "tp-spawn-budget",
        threadId: "thread-tp-spawn",
        prompt: "SPAWN_BUDGET_FIXTURE",
        turnPolicy: policy,
        tools: [subagentTool],
      }),
    );
    expect(events.at(-1)).toEqual({ type: "done", text: "SPAWN_SUSPENDED_NO_HELPER" });
    // AG-02: native helper delegation is suspended, so even though the request offers
    // run_subagent and a permissive policy, no spawn tool is offered and no helper session
    // ever reaches the model; the model's direct agent_spawn attempt is refused (unregistered)
    // and never runs a backend fallback tool. The budget/depth enforcement this scenario used
    // to prove end-to-end is covered in-JVM by InterruptibleTaskRepositoryTest.
    const spawnRequests = modelRequests.filter((input) =>
      userText(input).includes("SPAWN_BUDGET_FIXTURE"),
    );
    for (const input of spawnRequests) {
      const offered = (input.tools ?? []).map((tool) => tool.function.name);
      for (const native of ["agent_spawn", "agent_send", "agent_list", "task_output", "task_cancel", "task_list"]) {
        expect(offered, `suspended run offered ${native}`).not.toContain(native);
      }
    }
    expect(
      modelRequests.some(
        (input) =>
          input.model === "turnpolicy-fixture" && userText(input).includes("SPAWN_BG_MARKER"),
      ),
    ).toBe(false);
    expect(subagentToolCalls).toEqual([]);

    // The wire payload is v2 with all four constraint groups, the tightened
    // effective values, and no intent/action/next-step classification fields.
    const wire = runRequests.at(-1)!.sent.turnPolicy;
    expect(wire.version).toBe("v2");
    expect(Object.keys(wire).sort()).toEqual(
      [
        "version",
        "interactive",
        "planning",
        "delegation",
        "ownership",
        "routingKind",
        "budget",
        "approval",
        "retry",
        "subagent",
      ].sort(),
    );
    expect(Object.keys(wire.budget).sort()).toEqual(
      [
        "maxTokens",
        "maxCostUsd",
        "maxDurationSec",
        "maxToolCalls",
        "maxChildAgents",
        "maxDepth",
      ].sort(),
    );
    // delegation.maxChildren stays 3 while the TypeScript-tightened budget
    // carries maxChildAgents 0 and maxDepth 1 (from a stored 5): Java executed
    // against the tightened values, as the refusal above proves.
    expect(wire.delegation.maxChildren).toBe(3);
    expect(wire.budget.maxChildAgents).toBe(0);
    expect(wire.budget.maxDepth).toBe(1);
    expect(wire.subagent).toEqual({ permissionInheritance: "subset-readonly" });
    expect(wire.approval).toEqual({ timeoutSec: 86_400, onTimeout: "expire" });
    expect(wire.retry.maxAuto).toBeGreaterThan(0);
    expect(Array.isArray(wire.retry.retryable)).toBe(true);
  }, 60_000);

  it("hides the whole subagent surface and refuses spawns when the tightened depth is zero", async () => {
    const base = resolveTurnPolicy({ source: "chat", ownerBotId: "bot-tp" });
    const orchestration = buildRunOrchestration({
      kind: "direct",
      ownerBotId: "bot-tp",
      responseMode: "single",
      execution: {
        ...orchestrationExecution(base),
        // delegation.maxDepth stays 1; the stored budget tightens it to zero.
        budget: { ...base.budget, maxDepth: 0 },
      },
    });
    const policy = turnPolicyFromRun({
      trigger: "user",
      ownerBotId: "bot-tp",
      orchestration,
    });
    expect(policy.delegation.mode).toBe("auto");
    expect(policy.budget.maxDepth).toBe(0);
    const events = await consume(
      request({
        runId: "tp-depth-zero",
        threadId: "thread-tp-depth",
        prompt: "DEPTH_ZERO_FIXTURE",
        turnPolicy: policy,
        tools: [subagentTool],
      }),
    );
    expect(events.at(-1)).toEqual({ type: "done", text: "DEPTH_ZERO_BOUND" });

    // Java hid every native spawn tool from the model for this policy.
    const depthRequests = modelRequests.filter((input) =>
      userText(input).includes("DEPTH_ZERO_FIXTURE"),
    );
    expect(depthRequests.length).toBeGreaterThanOrEqual(2);
    for (const input of depthRequests) {
      const offered = (input.tools ?? []).map((tool) => tool.function.name);
      for (const native of [
        "agent_spawn",
        "agent_send",
        "agent_list",
        "task_output",
        "task_cancel",
        "task_list",
      ]) {
        expect(offered).not.toContain(native);
      }
    }
    // Neither the synchronous nor the background attempt executed: no helper
    // session reached the model and no spawn ever reported success.
    expect(
      modelRequests.some((input) => userText(input).includes("DEPTH_ZERO_TASK")),
    ).toBe(false);
    for (const input of depthRequests) {
      expect(transcript(input)).not.toContain("status: ok");
    }
    expect(subagentToolCalls).toEqual([]);

    // The wire carried the untightened delegation depth next to the tightened
    // budget depth; Java computed the effective zero itself.
    const wire = runRequests.at(-1)!.sent.turnPolicy;
    expect(wire.delegation.maxDepth).toBe(1);
    expect(wire.budget.maxDepth).toBe(0);
  }, 60_000);

  it("reuses the stored policy across attempts; only an approved budgetOverride changes it", async () => {
    const orchestration = storedOrchestration();
    const first = turnPolicyFromRun({
      trigger: "user",
      ownerBotId: "bot-tp",
      orchestration,
    });
    const firstEvents = await consume(
      request({
        runId: "tp-resume-a",
        threadId: "thread-tp-resume",
        prompt: "RESUME_FIXTURE_A",
        turnPolicy: first,
      }),
    );
    expect(firstEvents.at(-1)).toEqual({ type: "done", text: "RESUME_A_OK" });

    // A user-approved raise is the only budget change a later Attempt may carry.
    const resumed = turnPolicyFromRun({
      trigger: "user",
      ownerBotId: "bot-tp",
      orchestration,
      budgetOverride: { maxTokens: 400_002 },
    });
    const secondEvents = await consume(
      request({
        runId: "tp-resume-b",
        threadId: "thread-tp-resume",
        prompt: "RESUME_FIXTURE_B",
        turnPolicy: resumed,
      }),
    );
    expect(secondEvents.at(-1)).toEqual({ type: "done", text: "RESUME_B_OK" });

    const [wireA, wireB] = runRequests.slice(-2).map((entry) => entry.sent.turnPolicy);
    expect({ ...wireB, budget: undefined }).toEqual({ ...wireA, budget: undefined });
    expect(wireB.budget).toEqual({ ...wireA.budget, maxTokens: 400_002 });

    // A non-increase override is ignored: the stored budget stays authoritative.
    const tampered = turnPolicyFromRun({
      trigger: "user",
      ownerBotId: "bot-tp",
      orchestration,
      budgetOverride: { maxTokens: 100, maxChildAgents: 99 },
    });
    expect(tampered.budget.maxTokens).toBe(wireA.budget.maxTokens);
    expect(tampered.budget.maxChildAgents).toBe(wireA.budget.maxChildAgents);
  }, 60_000);

  it("fails closed at the Java door when the v2 wire policy is malformed", async () => {
    wireTransform = (body) => {
      body.turnPolicy.subagent.permissionInheritance = "full";
      return body;
    };
    const policy = turnPolicyFromRun({
      trigger: "user",
      ownerBotId: "bot-tp",
      orchestration: storedOrchestration(),
    });
    try {
      await expect(
        consume(
          request({
            runId: "tp-malformed-wire",
            threadId: "thread-tp-malformed",
            prompt: "MALFORMED_WIRE_FIXTURE",
            turnPolicy: policy,
            tools: [subagentTool],
          }),
        ),
      ).rejects.toThrow(/422/);
    } finally {
      wireTransform = null;
    }
    const recorded = runRequests.at(-1)!;
    // TypeScript generated a valid policy; only the wire copy was corrupted.
    expect(recorded.original.turnPolicy.subagent.permissionInheritance).toBe("subset-readonly");
    expect(recorded.sent.turnPolicy.subagent.permissionInheritance).toBe("full");
    // Fail closed means no execution at all: the model never saw this Run and
    // no planning or delegation recovered.
    expect(
      modelRequests.some((input) => transcript(input).includes("MALFORMED_WIRE_FIXTURE")),
    ).toBe(false);
  }, 60_000);

  it("never restores planning or delegation from a corrupt stored v2 snapshot", async () => {
    const base = resolveTurnPolicy({ source: "chat", ownerBotId: "bot-tp" });
    const corrupt = buildRunOrchestration({
      kind: "direct",
      ownerBotId: "bot-tp",
      responseMode: "single",
      execution: {
        ...orchestrationExecution(base),
        // A malformed persisted v2 constraint block.
        budget: { ...base.budget, maxTokens: "lots" } as never,
      },
    });
    const policy = turnPolicyFromRun({
      trigger: "user",
      ownerBotId: "bot-tp",
      orchestration: corrupt,
    });
    expect(policy.planning.mode).toBe("disabled");
    expect(policy.delegation.mode).toBe("disabled");
    const events = await consume(
      request({
        runId: "tp-corrupt-snapshot",
        threadId: "thread-tp-corrupt",
        prompt: "CORRUPT_SNAPSHOT_FIXTURE",
        turnPolicy: policy,
        tools: [subagentTool],
      }),
    );
    expect(events.at(-1)).toEqual({
      type: "done",
      text: "CORRUPT_SNAPSHOT_NO_PLANNING",
    });
    // Java hid the native planning and delegation tools from the model entirely.
    const modelCall = modelRequests.find(
      (input) =>
        input.model === "turnpolicy-fixture" &&
        userText(input).includes("CORRUPT_SNAPSHOT_FIXTURE"),
    );
    const offered = (modelCall?.tools ?? []).map((tool) => tool.function.name);
    expect(offered).not.toContain("plan_enter");
    expect(offered).not.toContain("plan_write");
    expect(offered).not.toContain("plan_exit");
    expect(offered).not.toContain("agent_spawn");
    expect(runRequests.at(-1)!.sent.turnPolicy.planning).toBe("disabled");
    expect(runRequests.at(-1)!.sent.turnPolicy.delegation.mode).toBe("disabled");
  }, 60_000);
});
